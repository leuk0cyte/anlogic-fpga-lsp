    "/w2",
    "/w3",
    "/w4",
    "/wd",  # /wd4324
    "/we",  # /we4324
    "/wx",
    "/mt",
    "/md",
    "/ob",  # /Ob2
    "/o1",
    "/o2",
    "/od",
    "/ox",
    "/ot",  # /Otime
    "/oy",
    "/os",
    "/gl",
    "/gy",
    "/gm",
    "/zi",
    "/zi",
    "/rtc",
    "/guard:",
    "/analyze",
    "/bigobj",
    "/utf-8",
    "/sourceDependencies",
    "/external:w",
    "/showincludes",
    "/FC",
    "/FS",
    "/JMC",
    "/Yc",
    "/Yu",
    "/Y-",
    "/MP",
